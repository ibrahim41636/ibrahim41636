/** Prefix a site path for the given language. Paths are written without the /ar prefix. */
export function href(lang: Lang, path = "/"): string {
  const clean = path.startsWith("/") ? path : `/${path}`;
  return lang === "ar" ? `/ar${clean === "/" ? "/" : clean}` : clean;
}

/** Strip the language prefix from a pathname (used by the language switcher and hreflang). */
export function basePath(pathname: string): string {
  return pathname.replace(/^\/ar(?=\/|$)/, "") || "/";
}

