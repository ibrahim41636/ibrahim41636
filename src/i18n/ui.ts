export function formatDate(lang: Lang, d: Date) {
  return new Intl.DateTimeFormat(lang === "ar" ? "ar-SA-u-ca-gregory-nu-latn" : "en-GB", { year: "numeric", month: "long", day: "numeric" }).format(d);
}
